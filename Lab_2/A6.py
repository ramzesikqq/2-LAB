# Считываем количество секунд
n = int(input("Введите количество секунд: "))

# 1. Вычисляем часы 
hours = (n // 3600) % 24

# 2. Вычисляем минуты 
minutes = (n % 3600) // 60

# 3. Вычисляем секунды 
seconds = n % 60

# 4. Выводим результат с форматированием
# :02d означает: вывести целое число (d), дополнив его нулями (0) до ширины в 2 символа (2)
print(f"{hours:02d}:{minutes:02d}:{seconds:02d}")