expressions = [
    "'123e'",                              # 1. Строка
    "'91.4'",                              # 2. Строка
    "524.345 ** 435345345311145345",       # 3. Огромное число с плавающей точкой
    "'7.1 + 4'",                           # 4. Строка
    "'4' - 2",                             # 5. Вычитание числа из строки
    "'4 - 2'",                             # 6. Строка
    "'42'",                                # 7. Строка
    "-12.12"                               # 8. Отрицательное число с плавающей точкой
]

print("Результаты проверки преобразования в int():\n")

for i, expr in enumerate(expressions, 1):
    print(f"Пункт {i}: {expr}")
    
    try:
        # Сначала вычисляем само выражение (чтобы '4' - 2 вызвало ошибку, как в задании)
        val = eval(expr)
        
        # Пытаемся преобразовать результат в int
        try:
            result = int(val)
            print(f"  -> Можно. Результат: {result}")
        except (ValueError, TypeError) as e:
            print(f"  -> Нельзя. Ошибка int(): {type(e).__name__}: {e}")
            
    except Exception as e:
        # Если ошибка произошла еще до int() (например, при вычитании строки)
        print(f"  -> Нельзя. Ошибка вычисления выражения: {type(e).__name__}: {e}")
        
    print("-" * 50)