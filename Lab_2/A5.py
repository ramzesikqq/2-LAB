
a = int(input("Введите число A: "))
b = int(input("Введите число B: "))
# Оператор % (остаток от деления) возвращает 0, если число делится нацело.
# Выражение (a % b == 0) даст True (что равно 1), если делится, и False (0), если нет.
# Если 0 (False) -> берем первый элемент "NO"
# Если 1 (True)  -> берем второй элемент "YES"
result = ["NO", "YES"][a % b == 0]
print(result)